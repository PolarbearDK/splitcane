REAL(8) FUNCTION BMOMENT(NEYX,N1,ZEYE,XYF,FF,NELX,XL,XG,L)
REAL(8) ZEYE(NEYX),FF(2,NEYX),XYF(2,NEYX),XL(0:NELX),XG(0:4,0:NELX)
XLL = XL(L)
X = XG(1,L)
Y = XG(2,L)
BM = 0.0D0
! WRITE(7,11111) 1,(FF(1,I),I=2,N1)
! WRITE(7,11111) 2,(FF(2,I),I=2,N1)
! 11111 FORMAT(' BMOM,FF(',I2,',*)=',12F8.2)
LOOP1: DO M = 2,N1
	IF (ZEYE(M) .LT. XLL) CYCLE LOOP1 
	BM = BM-FF(1,M)*(XYF(2,M)-Y)+FF(2,M)*(XYF(1,M)-X)
ENDDO LOOP1
! WRITE(7,12123) L,ZEYE(N1),XLL,X,Y,BM
! 12123 FORMAT(' BMOMENT:L,ZEY,XLL,X,Y,BM=',I4,6F15.4)
BMOMENT = BM
END
