SUBROUTINE CHEBUD(NGR,NPT,XX,YY,HH)
IMPLICIT INTEGER(4) (I-N) , REAL(8) (A-H,O-Z)
!
!   ********************************************************************
!     SUBROUTINE TIL UDGLATNING AF DATA MED CHEBYCHEVS METODE
!            VIGGO HOPPE, 1 JUNI 2000
!   ********************************************************************
!   NGR ER POLYNOMIEGRADEN+1  !!!!!!!!!
PARAMETER ( NGRAD=8)
REAL(8) XX(*),YY(*),HH(NGRAD)
REAL(8) TT(NGRAD),AA(NGRAD,NGRAD),FF(NGRAD)
LOGICAL ERR
WRITE(7,*) ' CHEBUDGLATNING:',NGR,NPT
RPI = 0.5D0/ATAN(1.0D0)
DO J = 1,NGR
	DO K = 1,NGR
		AA(J,K) = 0.0D0
	ENDDO
	FF(J) = 0.0D0
ENDDO
XJ = XX(1)
YJ = YY(1)
WRITE(7,*) ' CHEBUDGLATNING:',NGR,NPT,XJ,YJ
DO I = 2,NPT
	XI = XJ
	YI = YJ
	XJ = XX(I)
	YJ = YY(I)
	DX = XJ-XI
	X = (XJ+XI)/2
	Y = (YJ+YI)/2
!	WRITE(7,10000) I,DX,X,Y
10000 FORMAT(' CHEBUD  I,DX,X,Y:',I3,3F14.8)
	IF ( DX .LE. 0 .OR. ABS(X) .GE. 1.0D0 ) THEN
		WRITE(7,*) ' CHEBUD: DX ELLER X UDENFOR OMRÅDE; STOP'
	ENDIF
	DX = DX/SQRT(1.0D0-X*X)
	CALL CHEPOL(NGR,X,TT)
	DO J = 1,NGR
		T = TT(J)*DX
		DO K = 1,NGR
			AA(J,K) = AA(J,K)+T*TT(K)
		ENDDO
		FF(J) = FF(J)+T*Y
	ENDDO
ENDDO
!DO J = 1,NGR
!	DO K = 1,NGR
!		AA(J,K) = AA(J,K)*RPI
!	ENDDO
!	WRITE(7,11111) ' AA',(AA(J,K),K=1,NGR)
!ENDDO
!WRITE(7,11111) ' FF',(FF(K),K=1,NGR)
!11111 FORMAT(A3,8F10.6)
CALL SOLSYM(AA,FF,HH,NGR,NGRAD,1,1,.FALSE.,ERR)
IF (ERR) THEN
	WRITE(7,*) ' FEJL I CHEBUD(SOLSYM), STOP'
	STOP
ENDIF
END