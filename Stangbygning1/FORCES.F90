SUBROUTINE FORCES(FNX,FNY,NEYX,N1,HH,ZEYE,XYF,FF)
IMPLICIT INTEGER(4) (I-N) , REAL(8) (A-H,O-Z)
!	WRITE(7,*) ' KRÆFTER PÅ ØJERNE OG DERES POSITIONER'
REAL(8) ZEYE(NEYX),HH(NEYX),XYF(2,NEYX),FF(2,NEYX)
TREK = SQRT(FNX*FNX+FNY*FNY)
DX = (ZEYE(3)- ZEYE(2))
DY = (HH(3)- HH(2))
DD = TREK/SQRT(DX*DX+DY*DY)
WRITE(7,*) 'KRÆFTER I SNØRE FØR FØRSTE ØJE'
WRITE(7,*) 'F: TREK,DX,DY,DD',TREK,DX,DY,DD
! 
GX = DD*DX
GY = DD*DY
XK = XYF(1,2)
YK = XYF(2,2)
DO J = 3,N1-1
	K = J-1
! NÆSTE ØJE
   XJ = XYF(1,J)
   YJ = XYF(2,J)
   DX = XJ-XK
   DY = YJ-YK
   DD = TREK/SQRT(DX*DX+DY*DY)
   FX = DD*DX
   FY = DD*DY
 	WRITE(7,12340) K,J,XK,YK,XJ,YJ,GX,FX,GY,FY
 12340 FORMAT(' F: XYF, J,K', 2I3,4F10.2,4F10.6)
   FF(1,K) = FX-GX
   FF(2,K) = FY-GY
   WRITE(7,12345) K,FF(1,K),FF(2,K),XK,YK
   XK = XJ
   YK = YJ
	GX = FX
	GY = FY
ENDDO
 WRITE(7,12340) K,J,XK,YK,XJ,YJ,GX,FNX,GY,FNY
FF(1,N1) = FNX-GX
FF(2,N1) = FNY-GY
 WRITE(7,12345) N1,FF(1,N1),FF(2,N1),XYF(1,N1),XYF(2,N1)
12345 FORMAT(I3,' FX=',F12.7,' FY=',F12.7,&
				' X=',F8.2,' Y=',F8.2) 
END