SUBROUTINE STANGINIT
USE DFLIB
USE STANGMOD
IMPLICIT INTEGER(4) (I-N) , REAL(8) (A-H,O-Z)
!
!   ********************************************************************
!     SUBROUTINE TIL INITIERING AF BEREGNING AF SPLICANE FISKESTÆNGER:
!            VIGGO HOPPE, 20 FEBRUAR 2000
!  ***   1' input linie ************************************************
!     ANTAL KANTER                  : NKANT > 2
!     ANTAL ØJER                    : NEYE  > 2
!     ANTAL ELEMENTER I STANGEN     : 30 < NELE < NELX
!  ***   2' input linie ************************************************
!     FORHOLD MELLEM AFSTANDEN MELLEM DE TO ØVERSTE OG DE TO
!     NEDERSTE ØJER                 : REYE
!		HVIS REYE=0 INDLÆSES ØJEPLACERINGEN
!     ELASTICITETSMODUL             : EMOD  FOR MATERIALET       N/mm**2
!     MASSEFYLDE                    : RHO                        g/cm**3
!     TRÆK I SNØRE                  : NYTRIS                       N
!     SNØRENS VINKEL MED HÅNDTAGET  : RISH=NYVISH*RAD        ca. PI/2
!     VINKEL MELLEM STANGENS TANGENT I SPIDSEN OG
!     HÅNDTAGET                     : RISP=NYVISP*RAD        ca. PI/3
!     SPIRALPARAMETER, NORMALENS VINKEL MED RADIUSVEKTOR : RALF=RAD*ALFA ,
!     RALF KAN VÆRE NEGATIV, RALF = 0 SVARER TIL CIRKELFORMET UDBØJNING.
!     JO MERE POSITIV RALF JO STIVERE STANG:
!     D.V.S. MINDRE VANDRET UDBØJNING FOR SAMME KRAFT
!  ***   3' input linie ************************************************
!     TOTAL STANGLÆNGDE             : STAL                       mm
!     LÆNGDE AF HÅNDTAG,            : HAND                       mm
!     TOTAL STANGLÆNGDE             : STAL                       mm
!     LÆNGDE AF HÅNDTAG,            : HAND                       mm
!     AFSTAND FRA OVERKANT AF HÅNDTAG,
!     TIL NEDERSTE ØJE              : AFST                       mm
!     MINIMUM DIAMETER AF STANG     : SPIDS                      mm
!
!  ***   4' input linie ************************************************
!     FORHOLD MELLEM AFSTANDEN MELLEM DE TO ØVERSTE OG DE TO
!     NEDERSTE ØJER                 : REYE
!		HVIS REYE=0 INDLÆSES ØJEPLACERINGEN
!     HØJDE AF ØVERSTE ØJE          : HEY1                       mm
!     HØJDE AF NEDERSTE ØJE         : HEY2                       mm
!     LÆNGDE AF FERRULE             : FERL                       mm
!     MIN AFST. MLM. ØJE OG FERRULE : AFERL                      mm
!     DEN ANBRINGES SÅ NÆR MIDTEN SOM MULIGT OP TIL NÆRMESTE ØJE OG REGNES STIV.
!     DEN MEDTAGES FØRST I BJÆLKEBEREGNINGEN EFTER INITIALISERINGSPROGRAMMET
!     AFSTAND MELLEM SKRUER         : AJIG                       mm    I HØVLELÆRE (JIG)
!  ***   5' input linie ************************************************
!     SNØRENS VINKEL MED HÅNDTAGET  : NYVISH       ca. 90 grader
!     VINKEL MELLEM STANGENS TANGENT I SPIDSEN OG
!     HÅNDTAGET                     : VISP       ca. 60 grader
!     SPIRALPARAMETER, NORMALENS
!     VINKEL MED RADIUSVEKTOR       : ALFA , NORMALT >0, MEN ALFA KAN VÆRE NEGATIV,
!     ALFA = 0 SVARER TIL CIRKELFORMET UDBØJNING. STOR POSITIV ALFA GIVER STIV STANG:
!     D.V.S. MINDRE VANDRET UDBØJNING FOR SAMME KRAFT
!
!   *****  output tabeller og tilsvarende plot *************************
!     koordinatsystemets begyndelsespunkt ligger nederst i håndtaget,
!     derfor begynder udbøjningen først efter håndtaget 
!   ********************************************************************
!
PARAMETER ( NGRAD=8)
REAL(8) TT(NGRAD),GG(NGRAD),XX(NELX+1),YY(NELX+1)
CHARACTER*70 CHR
LOGICAL SPIRAL,FEJL
	WRITE(7,*) 'STANGENS DATA:'
	WRITE(6,11111) NKANT,NEYE,REYE,NELE,EMOD,RHO,&
	NYTRIS,NYVISH,VISP,ALFA,HEY1,HEY2
	WRITE(7,11111) NKANT,NEYE,REYE,NELE,EMOD,RHO,&
	NYTRIS,NYVISH,VISP,ALFA,HEY1,HEY2
	WRITE(6,22222) STAL,HAND,AFST,SPIDS,AJIG,FERL,AFERL
	WRITE(7,22222) STAL,HAND,AFST,SPIDS,AJIG,FERL,AFERL
11111 FORMAT(I2,'-KANTET STANG MED',I3,' ØJER, ',&
	' SOM ER SAT I AFSTANDSFORHOLDET:',F9.4,/,&
	' CA. ANTAL ELEMENTER I STANGEN:',I6,/,&
   ' ELASTICITETSMODUL.',F10.1,'  MASSEFYLDE',F10.4,/,&
   ' TRÆK I SNØREN',F9.2,' SOM DANNER VINKLEN',F7.2,&
   ' GRADER MED HÅNDTAGET.',/,' STANGENS SPIDS DANNER VINKLEN',F8.2,&
   ' GRADER MED HÅNDTAGET VED FULDT TRÆK',/,&
   ' FORMPARAMETER=            ',F10.2,/,&
	' HØJDE AF ØJE VED SPIDS   ',F10.1,/,&
	' HØJDE AF ØJE VED HÅNDTAG ',F10.1 )
!
	IF (NYVISH .LE. VISP) THEN
		WRITE(6,*) 'SNØRENS VINKEL MINDRE END SPIDSENS'
		WRITE(7,*) 'SNØRENS VINKEL MINDRE END SPIDSENS'
		STOP
	ENDIF
22222 FORMAT(' STANGLÆNGDE=               ',F8.1,/,&
             ' HÅNDTAGETS LÆNGDE          ',F8.1,/,&
             ' AFSTAND TIL NEDERSTE ØJE   ',F8.1,/,&
             ' DIAMETER VED SPIDS=        ',F8.1,/,&
             ' AFSTAND MELLEM STILLESKRUER',F8.1,/,&
             ' LÆNGDE AF FERULE=          ',F8.1,/,&
             ' MIN. AFSTAND ØJE-FERULE=   ',F8.1)
!
!  FORMPARAMETER
RALF = ALFA*RAD
!  SPIDSEN DANNER VINKLEN VISP GRADER MED HÅNDTAGET 
RISP = VISP*RAD          ! TIL RADIANER
!  SNØREN DANNER VINKLEN NYVISH GRADER MED HÅNDTAGET 
RISH = NYVISH*RAD         ! TIL RADIANER
!     STANG OVER HÅNDTAGET
STAN = STAL-HAND
!     DEL AF STANG HVOR ØJER FORDELES
STAM = STAN-AFST
!     STANG OVER HÅNDTAGET
STAN = STAL-HAND
!
!     HALVE SPLITVINKEL I RADIAN
ANKA = PI/NKANT
!     FOR RKANT = 1.0 ER AFSTAND FRA CENTRUM TIL FLADEN
HIGH = DCOS(ANKA)
!     FOR RKANT = 1 ER BREDDEN AF FLADEN
BRED = DSIN(ANKA)
IF ( MOD(NKANT,2) .NE. 0 ) THEN
	DIAM = HIGH+1.0_8
ELSE
	DIAM = HIGH*2
ENDIF
RMIN = SPIDS/DIAM
AREAL = NKANT*HIGH*BRED
AO = PI
AI = AO*HIGH**2
BO = AO/4
BI = BO*HIGH**2
FNUX = 0.0D0
FNUY = 0.0D0
10101 FORMAT(' FOR YDERRADIUS = 1 ER KONSTANTER FOR:'/&
23X,'OMSKEVEN CIRKEL',6X,'AKTUELT TVÆRSNIT',6X,'INDSKREVEN CIRKEL'/&
'    AREALER:    ',3F22.13/&
' INERTIMOMENTER:',3F22.13/)
BIMO = AREAL*(6.0_8-BRED**2)/24
WRITE(7,10101) AO,AREAL,AI,BO,BIMO,BI
BRED = BRED*2.0_8
WRITE(7,33333) HIGH,BRED,AREAL,BIMO
33333 FORMAT(' DIMENSIONER AF SPLITTEN FOR STØRSTE RADIUS RKANT = 1.0'&
       ,/,'   HIGH=',F8.5,'  BRED=',F8.5,'  AREAL=',F8.5,&
       ' INERTIMOMENT=',D12.5)
WRITE(7,44440) NEYE,REYE
44440 FORMAT(/,' PLACERING AF HÅNDTAGET OG DE',I3,' ØJER,',/&
					' FORHOLD MELLEM MINDSTE OG STØRSTE AFSTAND:',F9.5)
!     OPDELING AF STANG. SPIDS VED X = STAL.
NN = NEYE-1
N1 = NEYE+1
ZEYE(1) = HAND
X = HAND+AFST
ZEYE(2) = X
 WRITE(7,44444) -1,0.0,STAL
 WRITE(7,44445) HAND
 WRITE(7,44444) 0,ZEYE(1),STAL-ZEYE(1)
 WRITE(7,44445) AFST
 WRITE(7,44444) 1,ZEYE(2),STAL-ZEYE(2)
IF (REYE .LT. 0.01D0) THEN
!	ØJEPLACERINGEN ER BRUGERDEFINERET
	READ(2,*) (ZEYE(I),I=2,N1)
	A = ZEYE(2)
	IF ( A .LT. STAL*0.00001) THEN
!	BAGLÆNS INDLÆSNING
		MM = NEYE/2-1
		N2 = NEYE+2
		DO I = 0,MM
			M = 2+I
			N = N1-I
			A = ZEYE(M)
			B = ZEYE(N)
			ZEYE(M) = B
			ZEYE(N) = A
		ENDDO
		A = ZEYE(2)
	ENDIF
!	CHECK RÆKKEFØLGE
	FEJL = .FALSE.
	A = ZEYE(2)
	X = HAND+AFST
	IF ( ABS(A-X) .GT. 0.0001 ) THEN
		WRITE(7,44552) X,A
44552	FORMAT(' Nederste øje IKKE placeret i (håndtag+afstand)=',2F10.2)
		FEJL = .TRUE.
	ENDIF 
	DO I = 3,N1
		B = ZEYE(I)
		IF ( A .GE. B ) THEN
			WRITE(7,44550) A,B
			FEJL = .TRUE.
44550		FORMAT(' Øjerne placeret i',2F10.2,' ikke i rækkefølge!')
		ENDIF
		D = B-A
		WRITE(7,44445) D
		WRITE(7,44444) I-1,B,STAL-B
		A = B
	ENDDO
	IF ( ABS(A-STAL) .GT. 0.0001 ) THEN
		WRITE(7,44551) STAL,A
44551	FORMAT(' Øverste øje IKKE placeret i stanglængde=',2F10.2)
		FEJL = .TRUE.
	ENDIF 
	IF ( FEJL ) STOP
ELSE
	IF (REYE .EQ. 1.0D0) THEN
		A = STAM/NN
		DO I = 3,N1
			X = X+A
			WRITE(7,44445) A
			WRITE(7,44444) I-1,X,STAL-X
			ZEYE(I) = X
		ENDDO
	ELSE
		PP = 1.0D0/(NEYE-2)
		REY = REYE**PP
		A = REYE*STAM*(REY-1)/(REY**NN-1)
		DO I = 3,N1
			X = X+A
			WRITE(7,44445) A
			WRITE(7,44444) I-1,X,STAL-X
			ZEYE(I) = X
			A = A/REY
		ENDDO
	ENDIF
ENDIF
44444 FORMAT(I3,F12.2,F18.2)
44445 FORMAT(12X,F12.2)
!  PLACER FERULE
HALVST = STAL/2
ELENG = STAL/NELE
L = 0
X1 = 0.0D0
XL(0) = 0.0D0
XI(0,0) = 0.0D0
XI(1,0) = 0.0D0
XI(2,0) = 0.0D0
!  BEREGN HØJDE AF ØJER OG PLACER FERULE
DO I = 1,N1
	HH(I) = ((ZEYE(I)-ZEYE(2))*HEY1+(ZEYE(N1)-ZEYE(I))*HEY2)/STAM
	XYE(1,I) = ZEYE(I)
	XYE(2,I) = HH(I)
   X = X1
   X2 = ZEYE(I)
   DXI = X2-X1
	NXI = INT(DXI/ELENG)
	NXI = MAX(3,NXI)
   DX = DXI/NXI
   IF ( X2 .EQ. HAND ) NHAND = NXI
   IF ( X1 .LT. HALVST .AND. X2 .GE. HALVST ) THEN
!     PLACER FERULE
		WRITE(7,*) '  MED FERULE'
		SFERL = FERL+2*AFERL
		IF ( DXI .LT. SFERL) THEN
			WRITE(6,*) SFERL,DXI
			WRITE(7,*) SFERL,DXI
90000 FORMAT(' STOP, FOR LANG FERULE+AFSTANDE=',F9.2,/,&
				 '            AFSTAND MELLEM ØJER=',F9.2)
			STOP
		ENDIF
		XF1 = HALVST-FERL/2
		XF2 = HALVST+FERL/2
		DXF1 = XF1-X1
		DXF2 = X2-XF2
		IF (DXF1 .LT. AFERL ) THEN
			XF1 = X1+AFERL
			XF2 = XF1+FERL
		ELSEIF (DXF2 .LT. AFERL ) THEN
			XF2 = X2-FERL
			XF1 = XF2-AFERL
		ENDIF
		DXF1 = XF1-X1
		DXF2 = X2-XF2
		JFER1 = INT(DXF1/DX)
		JFER1 = MAX(1,JFER)
		JFER2 = INT(DXF2/DX)
		JFER2 = MAX(1,JFER2)
		DXF = DXF1/JFER1
		DO J = 1,JFER1
			L = L+1
			X = X+DXF
			XL(L) = X
			WRITE(7,*) L,XL(L)
		ENDDO
		L = L+1
		X = X+FERL
		XL(L) = X
		LFERL = L
		WRITE(6,88888) XF1,XF2,STAL-XF1,STAL-XF2
		WRITE(7,88888) XF1,XF2,STAL-XF1,STAL-XF2
88888 FORMAT(' FERULE PLACERET MELLEM ',2(F9.2,' , '),' FRA HÅNDTAG',/,& 
				 ' FERULE PLACERET MELLEM ',2(F9.2,' , '),' FRA SPIDS')
		WRITE(7,*) L,XL(L)
		DXF = DXF2/JFER2
		DO J = 1,JFER2
			L = L+1
			X = X+DXF
			XL(L) = X
			WRITE(7,*) L,XL(L)
		ENDDO
	ELSE
		WRITE(7,*) ' UDEN FERULE'
		DO J = 1,NXI
			L = L+1
			X = X+DX
			XL(L) = X
			WRITE(7,*) L,XL(L)
		ENDDO
	ENDIF
   X1 = X
	XI(0,L) = 0.0D0
	XI(1,L) = X
	XI(2,L) = 0.0D0
ENDDO
XL(L+1) = 2*STAL
! WRITE(7,*) ' EMODUL 0:',EMOD
NEL = L
WRITE(7,*) ' ANTAL ELEMENTER:',NEL
L = 0
XYE(1,1) = HAND
XYE(2,1) = 0.0D0
20002 FORMAT(1X,A11,I3,4F15.8)
DO L = 0,NEL
   XD(0,L) = 0.0D0
   XG(0,L) = 0.0D0
   XD(1,L) = XL(L)
   XG(1,L) = XL(L)
   XI(1,L) = XL(L)
   XD(2,L) = 0.0D0
   XG(2,L) = 0.0D0
   XI(2,L) = 0.0D0
ENDDO
! 
IF ( SPIDS .LT. 0.0001) THEN
!	INDLÆS PUNKT OG STANGTYKKELSE, ET PAR PÅ HVER LINIE
NPT = 0
C = 0.0D0
FEJL = .FALSE.
LOOP1: DO WHILE ( NPT .LT. NELX )
		READ(2,54321,ERR=100,END=200) CHR
54321 FORMAT(A70)
!		WRITE(7,*) ' CHR:',CHR
		B = C
		READ(CHR,*) C,D
		NPT = NPT+1
		IF ( NPT .EQ. 2 ) FT = SIGN(1.0,C-B)
		IF ( NPT .GT. 2 .AND. FT*(C-B) .LT. 0.0 ) THEN
			WRITE(7,*) ' KOORDINATER IKKE I RÆKKEFØLGE:',NPT,B,C
			FEJL = .TRUE.
		ENDIF
		IF ( B .GT. C ) THEN
			WRITE(7,*) ' TYKKELSER IKKE I RÆKKEFØLGE:', NPT,B,C
			FEJL = .TRUE. 
		ENDIF
		XX(NPT) = 2*C/STAL-1.0D0
!     DIAMETERN REGNES SOM MÅLET OVER KANTERNE
		YY(NPT) = D*0.5D0
!		YY(NPT) = D/DIAM
!		WRITE(7,*) NPT,XX(NPT),D,YY(NPT)
54322 FORMAT(' NPT,XX(NPT),D,YY(NPT)',I3,3F15.4)
		CYCLE LOOP1
100	WRITE(7,*) ' FEJL VED INDLÆSNING, STOP!',NPT
		STOP 
	ENDDO LOOP1
200	NGR = 6
	NP1 = NPT+1
	NP2 = NPT/2
	WRITE(7,*) ' NPT:',NPT
	IF ( YY(1) .LT. YY(NPT) ) THEN 
		WRITE(7,*) ' TALLENE BYTTES'
		DO I = 1,NP2
			A = YY(I)
			YY(I)= YY(NP1-I)
			YY(NP1-I) = A
			A = XX(I)
			XX(I)= XX(NP1-I)
			XX(NP1-I) = A
		ENDDO
	ENDIF
	IF ( XX(1) .GT. XX(NPT) ) THEN 
		WRITE(7,*) ' TALLENE INDLÆST FRA DEN SPIDSE ENDE'
		DO I = 1,NPT
			XX(I)= -XX(I)
		ENDDO
	ENDIF
	WRITE(7,*) ' GRAD OG ANTAL PUNKTER :',NGR,I
	CALL CHEBUD(NGR,NPT,XX,YY(1),GG)
	DO I = 0,NEL
		X = 2*XL(I)/STAL-1.0D0
		CALL CHEPOL(NGR,X,TT)
		R = 0.0D0
		DO J = 1,NGR
			R = R+TT(J)*GG(J)
		ENDDO
		RR(I) = R
!		WRITE(7,*) ' CHEB.POL',I,X,R
	ENDDO
ELSE
	IF (RALF .EQ. 0.0D0) THEN
		SPIRAL = .FALSE.
	!  CIRKELUDBØJNING, CENTRUM PÅ X-AKSEN
	!  STANGENS HÅNDTAG STILLES VANDRET, UDBØJNING (0,0)
		XCENTR = HAND
	!  YCENTR = RADIUS I CIRKLEN
		YCENTR = STAN/RISP
		CAPPA = 1.0D0/YCENTR
		WRITE(7,*) 
		WRITE(7,*) ' CIRKEL: XCENTR,YCENTR',XCENTR,YCENTR
		DV = RISP/STAN
		SALF = 0.0D0
		CALF = 1.0D0
		TALF = 0.0D0
		L = NHAND
!		WRITE(7,20002) ' CIRXYE(I):',1,HH(1),XYE(1,1),XYE(2,1)
		DO I = 2,N1
			ZEY = ZEYE(I)
			DO WHILE ( XL(L) .LE. ZEY )
				V = (XL(L)-HAND)*DV
				S = SIN(V)
				C = COS(V)
				XD(0,L) = V
				XI(0,L) = V
				XD(1,L) = XCENTR+YCENTR*S
				XI(1,L) = XCENTR+YCENTR*S
				XD(2,L) = YCENTR-YCENTR*C
				XI(2,L) = YCENTR-YCENTR*C
!	   		WRITE(7,20002) 'CIR XD(L): ',L,XD(0,L)*GRAD,XD(1,L),XD(2,L)
				L = L+1
			ENDDO
			R = YCENTR-HH(I)
			XYE(1,I) = XCENTR+R*S
			XYE(2,I) = YCENTR-R*C
!			WRITE(7,20002) ' CIRXYE(I):',I,HH(I),XYE(1,I),XYE(2,I)
		ENDDO
	ELSE
		SPIRAL = .TRUE.
	!  SPIRALUDBØJNING, CENTRUM IKKE OVER HÅNDTAGET ENDE
	!  FORHOLD MELLEM RADIER TIL CENTRUM:
		SALF = SIN(RALF)
		CALF = COS(RALF)
		TALF  = TAN(RALF)
	!   CAFA = 1.0D0/CALF
		FRA = EXP(RISP*TALF)
!		WRITE(7,77888) SALF,CALF,TALF,RISP,FRA
77888 FORMAT(' STANGINIT:SALF,CALF,TALF,RISP,FRA',5D14.6)
	!  BUELÆNGDEN ER L = (R2-R1)/SIN(RALF) UANSET POS. ELLER NEG. RALF
	!  R1 ER KRUMNINGSRADIUS I SPIDSEN, R2 VED HÅNDTAGET
		R1 = STAN*SALF/(FRA-1.0D0)
		R2 = R1*FRA
		XCENTR = R2*SALF+HAND
		YCENTR = R2*CALF
	!  SPIRALENS CENTRUM
!		WRITE(7,20002) ' SPIXYE:',1,XYE(1,1),XYE(2,1)
		L = NHAND
		DO I = 2,N1
			HEY = HH(I)
			ZEY = ZEYE(I)
			DO WHILE ( (XL(L)-ZEY) .LE. 1.0D-6 )
				R = R2-(XL(L)-HAND)*SALF
				V = -LOG(R/R2)/TALF
				XD(0,L) = V
				XI(0,L) = V
				U = RALF-V
				X = XCENTR-R*SIN(U)
				XD(1,L) = X
				XI(1,L) = X
				Y = YCENTR-R*COS(U)
				XD(2,L) = Y
				XI(2,L) = Y
	   		WRITE(7,20002) ' SPIXD :',L,XL(L),XD(0,L)*GRAD,XD(1,L),XD(2,L)
				L = L+1
			ENDDO
			XYE(1,I) = X-HEY*SIN(V)
			XYE(2,I) = Y+HEY*COS(V)
  		WRITE(7,20002) ' SPIXYE:',I,ZEY,V*GRAD,XYE(1,I),XYE(2,I)
		ENDDO
		WRITE(7,*) 
		WRITE(7,*) ' SPIRAL: XCENTR,YCENTR=',XCENTR,YCENTR
		WRITE(7,20002) ' N,R1,R2',L,R1,R2
		X2 = XCENTR-XI(1,NEL)
		Y2 = YCENTR-XI(2,NEL)
		WRITE(7,20002) ' N,x2,y2',NEL,X2,Y2
		WRITE(7,20002) ' N,x2,y2',L,X,Y
	ENDIF
ENDIF
 WRITE(7,*) ' EMODUL 2:',EMOD
!
FOLX = FNUX
FNUX = NYTRIS*COS(RISH)
FOLY = FNUY
FNUY = NYTRIS*SIN(RISH)
!	NEDERSTE ØJE HAR NR 2, BEREGN TRÆKVINKEL VED HÅNDTAG 
!	SÅ KRAFT PÅ ØJER ALDRIG BLIVER NEGATIV. TAN(T) = SIN(T)/COS(T)
TANT = (HEY1-HEY2)/(STAL-HAND-AFST)
CT = 1.0D0/SQRT(1.0D0+TANT**2)
ST = TANT*CT
F0X = CT*NYTRIS
F0Y = ST*NYTRIS
 WRITE(7,*) ' STANGINIT:NYTRIS,F0X,F0Y',NYTRIS,F0X,F0Y
FNX = FNUX
FNY = FNUY
TREK = NYTRIS
 WRITE(7,*) ' STANGINIT:RMIN,FNX,FNY',RMIN,FNX,FNY
IF ( RMIN .GT. 0.001 ) THEN
	CALL FORCES(FNX,FNY,NEYX,N1,HH,ZEYE,XYE,FF)
!
!  NU UDREGNES BØJNINGSMOMENTER OG KRUMNINGSRADIUS I ALLE DELEPUNKTER
	EMBIMO = EMOD*BIMO
	RMIN4  = EMBIMO*RMIN**4
	BLIMIT = CAPPA*RMIN4 
