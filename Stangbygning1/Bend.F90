SUBROUTINE BEND(EMOD,BIMO,NHAND,HAND,NEYX,N1,HH,ZEYE,XYF,XYG,FF,NELX,NEL,RR,XL,XG)
IMPLICIT INTEGER(4) (I-N) , REAL(8) (A-H,O-Z)
EXTERNAL BMOMENT
REAL(8) HH(NEYX),ZEYE(NEYX),FF(2,NEYX),XYF(2,NEYX),XYG(2,NEYX)
REAL(8) RR(0:NELX),XL(0:NELX),XG(0:4,0:NELX)
!
! ***************************************************************************
! SUBROUTINE TIL BEREGNING AF UDBØJNINGSKURVE FOR SPLITCANE FISKESTÆNGER MED
! OPGIVNE DIMENSIONER OG KRÆFTER, SOM IKKE NØDVENDIGVIS ER DE ENDELIGE. 
! DER BRUGES SIMPEL BJÆLKETEORI, MEN MED STORE DEFORMATIONER.
!            VIGGO HOPPE, 19 OKTOBER 2000
! ***************************************************************************
!
! WRITE(7,11111) 1,N1,(XYF(1,I),I=2,N1)
! WRITE(7,11111) 2,N1,(XYF(2,I),I=2,N1)
! 11111 FORMAT(' BEND,XYF(',I2,';2-',I2,')=',12F8.2)
S  = 0.0D0
C  = 1.0D0
V  = 0.0D0
X2  = HAND
Y2  = 0.0D0
DEX = 0.0D0
DEY = 1.0D0
IEYE = 2
XL2 = HAND
CAPPA2 = 0.0D0
LOOP1: DO L = NHAND,NEL
	GEX = DEX
	GEY = DEY
	X1 = X2
	Y1 = Y2
	XL1 = XL2
	XL2 = XL(L)
	DL = XL2-XL1
	BM = BMOMENT(NEYX,N1,ZEYE,XYF,FF,NELX,XL,XG,L)
	XG(3,L) = BM
	R = RR(L)
	WM = BIMO*R**3
	CAPPA1 = CAPPA2
!	CAPPA = KRUMNING = 1/KRUMNINGSRADIUS
	CAPPA2 = BM/(EMOD*WM*R)
	SIGMA = BM/WM
	XG(4,L) = SIGMA
	IF ( SIGMA .GT. SIGMAX ) THEN
		SIGMAX = SIGMA
		XIGM = XL2
	ENDIF
	IF ( L .LE. NHAND ) CYCLE LOOP1 
	DX = DL
	IF ( BM .LE. 0.0D0 .OR. (L .EQ. LFERL) ) THEN
		CAPPA = 0.0D0
		DV = 0.0D0
		DY = 0.0D0
	ELSE
!		CAPPA = CAPPA1+(CAPPA2-CAPPA1)*X/DL           LOKAL KRUMNING
!		THETA  = CAPPA1*X+(CAPPA2-CAPPA1)*X**2/(2*DL) LOKAL VINKELDREJNING
!		Y = CAPPA1*X**2/2+(CAPPA2-CAPPA1)*X**3(6*DL)  LOKAL UDBØJNING
		DCAPPA = CAPPA2-CAPPA1
		DV = (CAPPA1+CAPPA2)*DL/2
		DY = (CAPPA1/2+DCAPPA/6)*DL*DL
	ENDIF
	X2 = X1+DX*C-DY*S
	Y2 = Y1+DX*S+DY*C
	V = V+DV
	S = SIN(V)
	C = COS(V)
	U = XG(0,L)
	XG(0,L) = V
	XG(1,L) = X2
	XG(2,L) = Y2
	IF ( ABS(ZEYE(IEYE)-XL2) .LT. 2.0D-8 ) THEN
		XYG(1,IEYE) = X2-HH(IEYE)*SIN(V)
		XYG(2,IEYE) = Y2+HH(IEYE)*COS(V)
!		WRITE(7,12344) IEYE,V*GRAD,XYG(1,IEYE),XYG(2,IEYE)
! 12344 FORMAT(' BEND: IEYE,XYG(J,IEYE)',I3,3F14.4)
		IEYE = IEYE+1
	ENDIF
!  WRITE(7,12340) L,XG(0,L)*GRAD,V*GRAD,XG(1,L),X2,XG(2,L),Y2,XL2
! 12340 FORMAT(' B: L,XG,XG',I3,2F10.6,4F10.2,F20.12)!
!	WRITE(7,12341) GM,BM,CAPPA2
! 12341 FORMAT(' B: BM,CAPPA:',2F10.2,2D14.6)
ENDDO LOOP1
DO I = 1,N1
	XYF(1,I) = XYG(1,I)
	XYF(2,I) = XYG(2,I)
ENDDO
!
END