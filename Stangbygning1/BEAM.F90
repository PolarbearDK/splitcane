SUBROUTINE BEAM
USE STANGMOD
IMPLICIT INTEGER(4) (I-N) , REAL(8) (A-H,O-Z)
EXTERNAL BEND
!
! ***************************************************************************
! SUBROUTINE TIL KORREKTION AF UDBØJNINGSKURVE FOR SPLITCANE FISKESTÆNGER MED
! OPGIVNE DIMENSIONER EFTER SIMPEL BJÆLKETEORI, MEN MED STORE DEFORMATIONER
!            VIGGO HOPPE, 19 MARTS 2000
! ***************************************************************************
!
PARAMETER ( PLIMIX = 0.05D0 )
CHARACTER*(7)       FMT
CHARACTER*(44)      str
!
!	NEDERSTE ØJE HAR NR 2, BEREGN TRÆKVINKEL VED HÅNDTAG 
!	SÅ KRAFT PÅ ØJER ALDRIG BLIVER NEGATIV. TAN(T) = SIN(T)/COS(T)
TANT = (HEY1-HEY2)/(STAL-HAND-AFST)
CT = 1.0D0/SQRT(1.0D0+TANT**2)
ST = TANT*CT
! ITERATIONSPRINCIP: KRÆFTER SÆTTES PÅ I TRIN, SÅLEDES AT FLYTNINGEN AF SPIDSEN
! ALDRIG BLIVER STØRRE END DULIM = PLIMIX*STAL (PLIMIX = CA.0.05 TESTES)
! HVERT TRIN SKAL KONVERGERE !
! XD ER ENDELEG DEFORMATION				XYE ER PLACERING AF DE TILSVARENDE ØJER
! XG ER GAMMEL DEFORMATION					XYG ER PLACERING AF DE TILSVARENDE ØJER
! XI ER DEN ITEREREDE DEFORMATION		XYI ER PLACERING AF DE TILSVARENDE ØJER
! ITERATIONSPARAMETER BETA
! NTRIN ER DET ANTAL TRIN, I HVILKE BELATNINGSÆNDRINGEN PÅLÆGGES
DF = SQRT((FNUX-FOLX)**2+(FNUY-FOLY)**2)
NTRIN = NINT(DF/REFF)+1
DBET = 1.0D0/NTRIN
! WRITE(7,*) ' BEAM:FOLX,FOLY:',FOLX,FOLY
! WRITE(7,*) ' BEAM:FNUX,FNUY:',FNUX,FNUY
! WRITE(7,*) ' BEAM:DF,NTRIN,DBET:',DF,NTRIN,DBET
DO L = 2,N1
	XYF(1,L) = XYE(1,L)
	XYF(2,L) = XYE(2,L)
ENDDO
DO L = NHAND,NEL
	XG(0,L) = XD(0,L)
	XG(1,L) = XD(1,L)
	XG(2,L) = XD(2,L)
	XG(3,L) = XD(3,L)
	XG(4,L) = XD(4,L)
ENDDO
DO N = 1,NTRIN
	BETA = N*DBET
	BENE = 1.0D0-BETA
	FNX = BETA*FNUX+BENE*FOLX
	FNY = BETA*FNUY+BENE*FOLY
	TREK = SQRT(FNX*FNX+FNY*FNY)
	F0X = CT*TREK
	F0Y = ST*TREK
	DU = 10000.0
	GX = XYG(1,N1)
	GY = XYG(2,N1)
	ITERA = 0
	DO WHILE ( DU .GT. 2.0D-4 )
	!	TRÆK I SNØREN VED START AF ITERATIONSTRINET
		! KRÆFTERNE PÅ STANGENS ØJER UDREGNES 
		CALL FORCES(FNX,FNY,NEYX,N1,HH,ZEYE,XYG,FF)
		CALL BEND(EMOD,BIMO,NHAND,HAND,NEYX,N1,HH,ZEYE,XYF,XYG,FF,NELX,NEL,RR,XL,XG)
		HX = XYG(1,N1)
		HY = XYG(2,N1)
		DU = SQRT((HX-GX)**2+(HY-GY)**2)
!		WRITE(7,23456) DU,GX,GY,HX,HY
! 23456 FORMAT(' BEAM:DU,XYF(J,N1),XYG(J,I)',5F12.4)
!		DO I = 2,N1
!			WRITE(7,12345) I,(XYF(J,I),XYG(J,I),J=1,2)
! 12345 FORMAT(' BEAM:L,XYF(J,I),XYG(J,I)',I3,5F12.4)
!		ENDDO
		GX = HX
		GY = HY
	ENDDO
ENDDO
DO L = NHAND,NEL
	XD(0,L) = XG(0,L)
	XD(1,L) = XG(1,L)
	XD(2,L) = XG(2,L)
	XD(3,L) = XG(3,L)
	XD(4,L) = XG(4,L)
ENDDO
!
END