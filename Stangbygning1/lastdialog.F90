SUBROUTINE LASTDIALOG
USE DFLOGM
USE STANGMOD
IMPLICIT INTEGER(4) (I-N) , REAL(8) (A-H,O-Z)
TYPE (dialog) dlg
INCLUDE 'resource.fd'
LOGICAL retdlg, retlog
CHARACTER(256) text
!
retdlg = DLGINIT( IDD_DIALOG2, dlg )
WRITE(text,'(F9.4)') TRIS 
retlog = DlgSet( dlg, IDC_EDIT_NYTRIS,TRIM(ADJUSTL(text)) )
WRITE(text,'(F8.2)') VISH
retlog = DlgSet( dlg, IDC_EDIT_NYVISH,TRIM(ADJUSTL(text)) )
intret = DLGMODAL (dlg)
WRITE(7,*) ' LASTDIALOG ',INTRET
IF ( INTRET .NE. IDOK ) THEN
	IF ( INTRET .EQ. IDCANCEL ) THEN
		WRITE(6,*) ' DIALOG2 CANCELLED, PROGRAM STOPPED'
		WRITE(7,*) ' DIALOG2 CANCELLED, PROGRAM STOPPED'
		WRITE(8,*) ' DIALOG2 CANCELLED, PROGRAM STOPPED'
	ELSE
		WRITE(7,*) ' DIALOG2 ERROR, PROGRAM STOPPED'
	ENDIF
	STOP
ENDIF
retlog = DlgGet( dlg, IDC_EDIT_NYTRIS,text )
read(text,*) NYTRIS
retlog = DlgGet( dlg, IDC_EDIT_NYVISH,text )
read(text,*) NYVISH
WRITE(7,11111) NYTRIS,NYVISH
RISH = NYVISH*RAD
FOLX = FNUX
FOLY = FNUY
FNUX = NYTRIS*COS(RISH)
FNUY = NYTRIS*SIN(RISH)
TREK = NYTRIS
11111 FORMAT(' LASTDIALOG:TRIS,VISH=',2F14.6)
END SUBROUTINE LASTDIALOG
