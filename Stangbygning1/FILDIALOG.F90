SUBROUTINE FILDIALOG
USE DFLOGM
USE STANGMOD
IMPLICIT INTEGER(4) (I-N)
IMPLICIT REAL(8) (A-H,O-Z)
TYPE (dialog) dlg
INCLUDE 'resource.fd'
LOGICAL retdlg, retlog
CHARACTER(256) text
!	BLANK ELLER UDEFINERET FIL 
retdlg = DLGINIT( IDD_DIALOG1, dlg )
FIL = 'stang'
WRITE (text,*) FIL
retlog = DlgSet( dlg, IDC_EDIT_FILE,TRIM(ADJUSTL(text)) )
intret = DLGMODAL (dlg)
WRITE(8,*) ' FILDIALOG INTRET',INTRET
IF ( INTRET .NE. IDOK ) THEN
	IF ( INTRET .EQ. IDCANCEL ) THEN
		WRITE(6,*) ' DIALOG1 CANCELLED, PROGRAM STOPPED'
		WRITE(8,*) ' DIALOG1 CANCELLED, PROGRAM STOPPED'
	ELSE
		WRITE(6,*) ' DIALOG1 ERROR, PROGRAM STOPPED'
		WRITE(8,*) ' DIALOG1 ERROR, PROGRAM STOPPED'
	ENDIF
	STOP
ELSE
	retlog = DlgGet( dlg, IDC_EDIT_FILE,text )
	FIL = ADJUSTL(text)
	ISTA = LEN_TRIM(FIL)
	WRITE(8,11111) ISTA,FIL
11111 FORMAT(' ORDLÆNGDE OG FILNAVN I DIALOG1 :',/,I3,' :',A80)
ENDIF
END SUBROUTINE FILDIALOG
